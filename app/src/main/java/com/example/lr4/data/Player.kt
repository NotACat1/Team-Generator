package com.example.lr4.data

import java.util.UUID

/**
 * Data-модель игрока, используемая в приложении.
 *
 * @property id Уникальный идентификатор игрока (UUID), используется для различения одноимённых игроков.
 * @property name Имя игрока, вводимое пользователем.
 * @property isPresent Флаг присутствия игрока (отмечается пользователем перед формированием команд).
 *
 * Примечание:
 *  - UUID генерируется автоматически при создании игрока, что гарантирует уникальность записей.
 *  - Благодаря этому можно безопасно редактировать и удалять конкретного игрока даже при повторяющихся именах.
 */
data class Player(
    val id: String = UUID.randomUUID().toString(),
    val name: String,
    val isPresent: Boolean = false
)
